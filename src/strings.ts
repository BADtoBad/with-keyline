export type Message = keyof typeof strings;
export function isChinese(preferences: Preferences): boolean {
  if (preferences.language !== "auto") return preferences.language === "zh";
  // getLanguage is optional on the supported older cores. No private storage.
  return typeof Host.getLanguage === "function" && /^zh/i.test(Host.getLanguage());
}
export function message(key: Message, zh: boolean): string { return strings[key][zh ? 1 : 0]; }
